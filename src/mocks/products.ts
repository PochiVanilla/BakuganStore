function buildProduct(seed: ProductSeed, index: number): Product {
  const slug = `${slugify(seed.name)}-${(index + 1).toString().padStart(3, '0')}`;
  const attributeMeta = ATTRIBUTE_META[seed.attribute];
  const seriesMeta = SERIES_META[seed.series];
  const extras = seed.extras ?? [];

  return {
    id: `prd-${(index + 1).toString().padStart(3, '0')}`,
    slug,
    name: `Bakugan ${seed.name}`,
    shortDescription: seed.blurb,
    description: [
      seed.blurb,
      `${seed.name} thuộc hệ ${attributeMeta.label} (${attributeMeta.element}), dòng ${seriesMeta.label} (${seriesMeta.years}). ${seriesMeta.description}`,
      `Chỉ số G-Power ${seed.gPower}G. Tình trạng: ${CONDITION_LABELS[seed.condition].toLowerCase()}. Mỗi sản phẩm đều được TD Bakugan kiểm tra cơ cấu bung nở, vệ sinh khoang nam châm và chụp ảnh thực tế trước khi lên kệ.`,
      'Hàng được đóng gói chống sốc hai lớp, có quay video khi đóng gói và hỗ trợ đổi trả trong 7 ngày nếu lỗi từ nhà sản xuất.',
    ].join('\n\n'),
    images: [0, 1, 2, 3].map((variant) => productPlaceholder(seed.name, seed.attribute, variant)),
    price: seed.price,
    originalPrice: seed.originalPrice,
    attribute: seed.attribute,
    series: seed.series,
    gPower: seed.gPower,
    condition: seed.condition,
    stock: seed.stock,
    soldCount: seed.soldCount,
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    createdAt: daysAgo(seed.addedDaysAgo),
    accessories: BASE_ACCESSORIES.map((name) => ({
      name,
      included: extras.includes(name) || name === 'Túi chống sốc',
    })),
    specs: [
      { label: 'Hệ (Attribute)', value: `${attributeMeta.label} — ${attributeMeta.element}` },
      { label: 'Dòng (Series)', value: `${seriesMeta.label} (${seriesMeta.years})` },
      { label: 'G-Power', value: `${seed.gPower} G` },
      { label: 'Tình trạng', value: CONDITION_LABELS[seed.condition] },
      { label: 'Chất liệu', value: 'Nhựa ABS cao cấp, lõi nam châm' },
      { label: 'Đường kính khi đóng', value: '~3,2 cm' },
      { label: 'Xuất xứ', value: 'Chính hãng, nhập khẩu' },
      { label: 'Bảo hành', value: 'Đổi trả 7 ngày nếu lỗi nhà sản xuất' },
    ],
    tags: [attributeMeta.label, seriesMeta.label, CONDITION_LABELS[seed.condition]],
    isFeatured: seed.featured ?? false,
    isBestSeller: seed.bestSeller ?? false,
    isRare: seed.rare ?? false,
  };
}

